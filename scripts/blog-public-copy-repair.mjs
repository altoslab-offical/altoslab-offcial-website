async function fetchJson(url, options = {}) {
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), Number.parseInt(process.env.BLOG_REPAIR_TIMEOUT_MS || "25000", 10));
  const response = await fetch(url, {
    ...options,
    signal: controller.signal,
    headers: {
      "Content-Type": "application/json",
      Accept: "application/json",
      "User-Agent": "ALTOS-LAB-public-copy-repair/1.0",
      ...(options.headers || {})
    }
  }).finally(() => clearTimeout(timeout));
  const text = await response.text();
  const payload = text ? JSON.parse(text) : {};
  if (!response.ok) {
    throw new Error(`${options.method || "GET"} ${url} failed: ${response.status} ${text}`);
  }
  return { payload, response };
}

async function login(root) {
  const pass = password();
  if (!pass) throw new Error("ALTOS_ADMIN_PASSWORD or ADMIN_PASSWORD is required");
  const { response } = await fetchJson(`${root}/api/admin/auth/login`, {
    method: "POST",
    body: JSON.stringify({ password: pass })
  });
  const setCookie = response.headers.get("set-cookie") || "";
  const match = setCookie.match(new RegExp(`(?:^|,\\s*)(${ADMIN_COOKIE}=[^;]+)`));
  if (!match?.[1]) throw new Error("Admin login did not return an altos_admin cookie");
  return match[1];
}

async function fetchPublicPosts(root, languageArg) {
  if (languageArg !== "all") {
    const { payload } = await fetchJson(`${root}/api/blog?language=${encodeURIComponent(languageArg)}&limit=120`);
    return payload.posts || [];
  }
  const batches = await Promise.all(
    BLOG_LANGUAGES.map(async (language) => {
      const { payload } = await fetchJson(`${root}/api/blog?language=${encodeURIComponent(language)}&limit=120`);
      return payload.posts || [];
    })
  );
  return batches.flat();
}

async function mapWithConcurrency(items, concurrency, worker) {
  const limit = Math.max(1, Math.min(Number.parseInt(String(concurrency || "1"), 10) || 1, 12));
  let cursor = 0;
  const runners = Array.from({ length: Math.min(limit, items.length) }, async () => {
    while (cursor < items.length) {
      const index = cursor;
      cursor += 1;
      await worker(items[index], index);
    }
  });
  await Promise.all(runners);
}

